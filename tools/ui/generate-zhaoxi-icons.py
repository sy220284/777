#!/usr/bin/env python3
"""Convert the shipped E8.17 artwork into native vector resources, preserving geometry.

SVG arc flags are single characters and may be adjacent (SVG 2 paths §9.3.9).
Android PathParser needs separated parameters; normalize them at generation time.
No SVG file is interpreted on the UI thread.
https://www.w3.org/TR/SVG2/paths.html
https://developer.android.com/develop/ui/views/graphics/vector-drawable-resources
"""
import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/design/zhaoxi/E8.17/icons'
PACK = ROOT / 'ui-pack-zhaoxi/src/main'
NUMBER = re.compile(r'[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?')
ARITY = dict(M=2, L=2, H=1, V=1, C=6, S=4, Q=4, T=2, A=7)

def normalize_path(data):
    result, index, command = [], 0, None
    while index < len(data):
        while index < len(data) and data[index] in ' ,\t\r\n': index += 1
        if index == len(data): break
        if data[index].isalpha():
            command = data[index]; index += 1
            if command.upper() == 'Z':
                result.append(command); command = None
                continue
        if command is None or command.upper() not in ARITY: raise ValueError('Unsupported SVG command')
        args = []
        for position in range(ARITY[command.upper()]):
            while index < len(data) and data[index] in ' ,\t\r\n': index += 1
            if command.upper() == 'A' and position in (3, 4):
                if index >= len(data) or data[index] not in '01': raise ValueError('Invalid SVG arc flag')
                args.append(data[index]); index += 1
            else:
                number = NUMBER.match(data, index)
                if number is None: raise ValueError(f'Incomplete SVG {command} at {index}: {data}')
                args.append(number.group()); index = number.end()
        result.append(command + ' ' + ' '.join(args))
        if command.upper() == 'M': command = 'L' if command == 'M' else 'l'
    return ' '.join(result)

def shape_path(node):
    name = node.tag.split('}')[-1]
    def f(key, default=0): return float(node.get(key, default))
    if name == 'path': return normalize_path(node.attrib['d'])
    if name == 'circle':
        x, y, r = f('cx'), f('cy'), f('r')
        return normalize_path(f'M{x-r} {y} A{r} {r} 0 1 0 {x+r} {y} A{r} {r} 0 1 0 {x-r} {y} Z')
    if name == 'rect':
        x, y, w, h = f('x'), f('y'), f('width'), f('height')
        rx, ry = f('rx'), f('ry', f('rx'))
        if rx == 0 or ry == 0: return normalize_path(f'M{x} {y} H{x+w} V{y+h} H{x} Z')
        return normalize_path(f'M{x+rx} {y} H{x+w-rx} A{rx} {ry} 0 0 1 {x+w} {y+ry} V{y+h-ry} A{rx} {ry} 0 0 1 {x+w-rx} {y+h} H{x+rx} A{rx} {ry} 0 0 1 {x} {y+h-ry} V{y+ry} A{rx} {ry} 0 0 1 {x+rx} {y} Z')
    raise ValueError(f'Unsupported SVG element {name}')

def generate():
    outputs, identifiers = {}, []
    for file in sorted(SOURCE.glob('*.svg')):
        if file.stem == 'sprite': continue  # sprite duplicates the 43 individual artworks
        svg = ET.fromstring(file.read_text())
        assert svg.attrib['viewBox'] == '0 0 24 24'
        paths = []
        for node in svg:
            style = dict(svg.attrib) | node.attrib
            def color(key):
                value = style.get(key, 'none')
                if value == 'none': return '#00000000'
                if value == 'currentColor': return '#FFFFFFFF'
                raise ValueError('Unsupported artwork color ' + value)
            attrs = {'pathData':shape_path(node), 'fillColor':color('fill'), 'strokeColor':color('stroke'),
                'strokeWidth':style.get('stroke-width', '0'), 'strokeLineCap':style.get('stroke-linecap', 'butt'),
                'strokeLineJoin':style.get('stroke-linejoin', 'miter')}
            paths.append('    <path ' + ' '.join('android:' + key + '=' + quoteattr(value) for key,value in attrs.items()) + ' />')
        stem = 'zx_' + file.stem.replace('-', '_')
        outputs[PACK / f'res/drawable/{stem}.xml'] = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from E8.17; run tools/ui/generate-zhaoxi-icons.py -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n' + '\n'.join(paths) + '\n</vector>\n'
        identifiers.append((file.stem, stem))
    kotlin = '// Generated by tools/ui/generate-zhaoxi-icons.py; do not edit.\npackage com.labteto.dshmobile.uipack.zhaoxi.components\n\nimport com.labteto.dshmobile.uipack.zhaoxi.R\n\nobject ZhaoxiIconResources {\n    val all: Map<String, Int> = mapOf(\n'
    kotlin += ''.join(f'        "{name}" to R.drawable.{stem},\n' for name,stem in identifiers)
    outputs[PACK / 'kotlin/com/labteto/dshmobile/uipack/zhaoxi/components/ZhaoxiIconResources.kt'] = kotlin + '    )\n}\n'
    return outputs

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); parser.add_argument('--self-test', action='store_true'); args = parser.parse_args()
    if args.self_test:
        assert normalize_path('M5 4h11l3 3v13a1 1 0 01-1 1H5a1 1 0 01-1-1V5a1 1 0 011-1z') == 'M 5 4 h 11 l 3 3 v 13 a 1 1 0 0 1 -1 1 H 5 a 1 1 0 0 1 -1 -1 V 5 a 1 1 0 0 1 1 -1 z'
        assert normalize_path('M0 0 1 2A1 2 30 103.5-.5 2 2 0 01-1-2') == 'M 0 0 L 1 2 A 1 2 30 1 0 3.5 -.5 A 2 2 0 0 1 -1 -2'
        assert normalize_path('M1e-3 -.2L.5+2') == 'M 1e-3 -.2 L .5 +2' 
    outputs = generate()
    changed = [path for path,content in outputs.items() if not path.exists() or path.read_text() != content]
    if args.check and changed: raise SystemExit('Generated icon resources differ: ' + ', '.join(str(x.relative_to(ROOT)) for x in changed))
    if not args.check:
        for path,content in outputs.items(): path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content)
    print(f'E8.17 native icons: {len(outputs)-1} artworks checked')
