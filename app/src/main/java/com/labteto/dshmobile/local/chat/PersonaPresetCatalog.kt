private fun presetPersona(
    name: String,
    portrait: String = "",
    lifeContext: String = "",
    stableTraitsText: String = "",
    worldSetting: String = "",
    franchise: String = "",
    timelinePosition: String = "",
    coreValues: List<String> = emptyList(),
    secondaryValues: List<String> = emptyList(),
    coreTensionCandidates: List<String> = emptyList(),
    knowledgeBoundary: List<String> = emptyList(),
    loreEntries: List<PersonaLoreEntry> = emptyList(),
    hardConstraints: List<String> = emptyList(),
    presetId: String = "",
): PersonaProfile {
    val life = presetLifeDetails(name)
    return PersonaProfile(
        name = name,
        portrait = portrait,
        lifeContext = lifeContext,
        attentionBiases = life.attentionBiases,
        attentionKeywords = PRESET_ATTENTION_KEYWORDS[name].orEmpty(),
        perceptionBlindSpots = life.perceptionBlindSpots,
        quirks = life.quirks,
        limitations = life.limitations,
        coreValues = (coreValues + secondaryValues)
            .map(String::trim).filter(String::isNotBlank).distinct().take(3),
        coreTension = coreTensionCandidates.firstOrNull()
            ?: PRESET_CORE_TENSIONS[name].orEmpty(),
        stableTraits = listOf(stableTraitsText).map(String::trim).filter(String::isNotBlank),
        worldSetting = worldSetting,
        franchise = franchise,
        timelinePosition = timelinePosition,
        knowledgeBoundary = knowledgeBoundary,
        // Keep the most relevant built-in anchor plus two searchable facts. The complete
        // life history stays in the core card; existing installed/user-edited books are untouched.
        loreEntries = (loreEntries.take(1) + supplementalPresetCanonLore(name, presetId))
            .distinctBy { it.id.ifBlank { it.title } },
        hardConstraints = hardConstraints,
        presetId = presetId,
    )
}


private fun compactPreset(
    id: String,
    franchise: String,
    name: String,
    summary: String,
    portrait: String,
    lifeContext: String,
    stableTraitsText: String,
    worldSetting: String,
    coreValue: String,
    loreTitle: String,
    loreContent: String,
    loreKeywords: List<String>,
    hardConstraints: List<String>,
): PersonaPreset = PersonaPreset(
    id = id,
    franchise = franchise,
    summary = summary,
    artwork = PersonaPresetArtwork(
        assetPath = "persona-presets/$id.webp",
    ),
    persona = presetPersona(
        name = name,
        portrait = portrait,
        lifeContext = lifeContext,
        stableTraitsText = stableTraitsText,
        worldSetting = worldSetting,
        franchise = franchise,
        timelinePosition = "默认采用通用无剧透阶段；只使用当前关系与用户已明确的剧情事实，不主动推进或泄露后续主线。",
        coreValues = listOf(coreValue),
        knowledgeBoundary = listOf(
            "只知道自己在当前时间线合理经历、被告知或公开可知的事情。",
            "用户未建立的后续剧情、隐藏信息和其他角色私下经历默认不知道。",
        ),
        loreEntries = listOf(
            PersonaLoreEntry(
                id = "$id-core",
                title = loreTitle,
                content = loreContent,
                keywords = loreKeywords,
                priority = 80,
            ),
        ),
        hardConstraints = hardConstraints,
        presetId = id,
    ),
)

